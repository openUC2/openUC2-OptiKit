/**
 * Generate TypeScript types from the normative optikit-core JSON Schemas.
 *
 * Source of truth: the Pydantic models in ../optikit-core (schema v0); this
 * script consumes their exported JSON Schema (schema/dist/) so the frontend
 * never hand-maintains the datamodel. Output is committed.
 *
 * Usage:  npm run gen:schema
 * Env:    OPTIKIT_CORE_SCHEMA_DIR — path to optikit-core/schema/dist
 *         (default: ../optikit-core/schema/dist relative to this repo)
 */

import { compile } from 'json-schema-to-typescript';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaDir = resolve(
  process.env.OPTIKIT_CORE_SCHEMA_DIR ?? join(repoRoot, '..', 'optikit-core', 'schema', 'dist'),
);
const outDir = join(repoRoot, 'src', 'model', 'dsn', 'generated');

mkdirSync(outDir, { recursive: true });

const schema = JSON.parse(readFileSync(join(schemaDir, 'design-decl.schema.json'), 'utf8'));

const banner = `/**
 * GENERATED by scripts/gen-schema-types.mjs from optikit-core schema v0
 * (${schema.$id ?? 'design-decl.schema.json'}). Do not edit by hand —
 * re-run \`npm run gen:schema\` after the Pydantic models change.
 */
`;

const ts = await compile(schema, 'DesignDecl', {
  bannerComment: banner,
  additionalProperties: true,
  style: { singleQuote: true },
});
writeFileSync(join(outDir, 'design-decl.ts'), ts);
console.log(`wrote src/model/dsn/generated/design-decl.ts (from ${schemaDir})`);

// Library records (WP-14 component editor edits these).
const componentSchema = JSON.parse(
  readFileSync(join(schemaDir, 'library-component.schema.json'), 'utf8'),
);
const componentTs = await compile(componentSchema, 'ComponentRecord', {
  bannerComment: banner,
  additionalProperties: true,
  style: { singleQuote: true },
});
writeFileSync(join(outDir, 'library-component.ts'), componentTs);
console.log(`wrote src/model/dsn/generated/library-component.ts (from ${schemaDir})`);
